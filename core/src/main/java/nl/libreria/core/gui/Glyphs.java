package nl.libreria.core.gui;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.FontDescription;
import net.minecraft.network.chat.FormattedText;
import net.minecraft.network.chat.MutableComponent;
import net.minecraft.network.chat.Style;
import net.minecraft.network.chat.TextColor;
import net.minecraft.resources.Identifier;
import nl.libreria.core.Libreria;

/**
 * The pictures of the Libreria resource pack that live in a font (libreria:ui): tooltip panels, menu frames, icons,
 * progress pips and exact spacing. Text is the only thing the server can place pixel-precisely on every client, so the
 * pack draws these as "letters". Generated by scripts/ui/generate.py; this class reads its glyph table and also knows
 * the exact width of Minecraft's default font, so cards can be sized to the pixel.
 */
public final class Glyphs {
	public static final FontDescription FONT = new FontDescription.Resource(Identifier.fromNamespaceAndPath("libreria", "ui"));

	private static final Map<String, int[]> GLYPHS = new HashMap<>();
	private static final Map<Integer, Integer> ADVANCE_BY_CP = new HashMap<>();
	private static final Map<Integer, Integer> WIDTHS = new HashMap<>();
	/** Item id (without "minecraft:") → {codepoint, tinted, advance} of its 16x16 icon in the top tooltip fonts. */
	private static final Map<String, int[]> ICONS = new HashMap<>();
	public static int hudLines = 12;
	private static int defaultWidth = 8;
	public static int lineHeight = 10;
	public static int padX = 6;
	public static int padTop = 6;
	public static int padBottom = 5;
	public static int minPanel = 2;
	public static int maxPanel = 14;
	/** Colour of a window's title in the pack's look, and of its shadow. */
	public static int titleColor = 0xECDCB4;
	public static int titleShadow = 0x140C06;
	/** Cards that belong to no place, and quiet text, in the pack's look. */
	public static int neutral = 0xC4CAD6;
	public static int muted = 0xA6ACB8;
	/** The heights (window y) at which the big item pictures ("ico.…") exist. */
	public static final java.util.Set<Integer> ICON_Y = new java.util.HashSet<>();

	static {
		try {
			JsonObject meta = read("/libreria/ui_glyphs.json");
			lineHeight = meta.get("lineHeight").getAsInt();
			padX = meta.get("padX").getAsInt();
			padTop = meta.get("padTop").getAsInt();
			padBottom = meta.get("padBottom").getAsInt();
			JsonArray range = meta.getAsJsonArray("panelLines");
			minPanel = range.get(0).getAsInt();
			maxPanel = range.get(1).getAsInt();
			for (var e : meta.getAsJsonObject("glyphs").entrySet()) {
				JsonArray a = e.getValue().getAsJsonArray();
				int[] g = {a.get(0).getAsInt(), a.get(1).getAsInt()};
				GLYPHS.put(e.getKey(), g);
				ADVANCE_BY_CP.put(g[0], g[1]);
			}
			if (meta.has("hudLines")) hudLines = meta.get("hudLines").getAsInt();
			if (meta.has("iconY")) meta.getAsJsonArray("iconY").forEach(e -> ICON_Y.add(e.getAsInt()));
			if (meta.has("look")) {
				JsonObject look = meta.getAsJsonObject("look");
				titleColor = look.get("title").getAsInt();
				titleShadow = look.get("titleShadow").getAsInt();
				if (look.has("neutral")) neutral = look.get("neutral").getAsInt();
				if (look.has("muted")) muted = look.get("muted").getAsInt();
			}
			if (meta.has("icons")) {
				for (var e : meta.getAsJsonObject("icons").entrySet()) {
					JsonArray a = e.getValue().getAsJsonArray();
					ICONS.put(e.getKey(), new int[] {a.get(0).getAsInt(), a.get(1).getAsInt(), a.size() > 2 ? a.get(2).getAsInt() : 17});
				}
			}
			JsonObject w = read("/libreria/font_widths.json");
			defaultWidth = w.get("default").getAsInt();
			String s = w.get("widths").getAsString();
			for (int i = 0; i < s.length(); ) {
				int cp = s.codePointAt(i);
				i += Character.charCount(cp);
				WIDTHS.put(cp, Integer.parseInt(s.substring(i, i + 2)));
				i += 2;
			}
		} catch (Exception e) {
			Libreria.LOG.error("Libreria: could not read the UI glyph table", e);
		}
	}

	private Glyphs() {
	}

	private static JsonObject read(String path) throws Exception {
		try (Reader r = new InputStreamReader(Glyphs.class.getResourceAsStream(path), StandardCharsets.UTF_8)) {
			return new Gson().fromJson(r, JsonObject.class);
		}
	}

	public static boolean has(String name) {
		return GLYPHS.containsKey(name);
	}

	/** The character of a glyph. */
	public static String g(String name) {
		int[] g = GLYPHS.get(name);
		return g == null ? "" : Character.toString(g[0]);
	}

	/** How far a glyph moves the cursor. */
	public static int advance(String name) {
		int[] g = GLYPHS.get(name);
		return g == null ? 0 : g[1];
	}

	/** Exactly {@code px} pixels of (possibly negative) space. */
	public static String space(int px) {
		StringBuilder sb = new StringBuilder();
		for (int k = 9; k >= 0; k--) {
			int v = 1 << k;
			while (Math.abs(px) >= v) {
				int step = px > 0 ? v : -v;
				sb.append(g(String.format("space%+d", step)));
				px -= step;
			}
		}
		return sb.toString();
	}

	/** A run of tiles (prefix + 64, 32 … 1) that is exactly {@code w} pixels wide. */
	public static String tiles(String prefix, int w) {
		StringBuilder sb = new StringBuilder();
		String back = g("space-1");
		for (int t = 64; t >= 1; t /= 2) {
			while (w >= t) {
				sb.append(g(prefix + t)).append(back);
				w -= t;
			}
		}
		return sb.toString();
	}

	/** Text in the UI font. */
	public static MutableComponent ui(String text) {
		return Component.literal(text).withStyle(s -> s.withFont(FONT).withBold(false).withItalic(false));
	}

	/** Text in the UI font, tinted (white = the picture's own colours). */
	public static MutableComponent ui(String text, int rgb) {
		return Component.literal(text).withStyle(s -> s.withFont(FONT).withBold(false).withItalic(false).withColor(TextColor.fromRgb(rgb)));
	}

	/** Exact width of a component in pixels, as the client will draw it (a key is measured as its usual name). */
	public static int width(Component c) {
		int[] total = {0};
		measure(c, Style.EMPTY, total);
		return total[0];
	}

	/** How wide the client's name of a key usually is ("Left Shift", or "Left Control" for those who moved it). */
	private static final java.util.Map<String, String> KEY_NAMES = java.util.Map.ofEntries(
			java.util.Map.entry("key.sneak", "Left Control"), java.util.Map.entry("key.sprint", "Left Control"),
			java.util.Map.entry("key.use", "Right Button"), java.util.Map.entry("key.attack", "Left Button"),
			java.util.Map.entry("key.pickItem", "Middle Button"), java.util.Map.entry("key.jump", "Space"));

	private static void measure(Component c, Style parent, int[] total) {
		Style style = c.getStyle().applyTo(parent);
		if (c.getContents() instanceof net.minecraft.network.chat.contents.KeybindContents k) {
			total[0] += width(Component.literal(KEY_NAMES.getOrDefault(k.getName(), "F")).withStyle(style));
		} else {
			c.getContents().visit((FormattedText.StyledContentConsumer<Object>) (st, text) -> {
				boolean ui = st.getFont() instanceof FontDescription.Resource r && r.id().getNamespace().equals("libreria");
				boolean bold = st.isBold();
				text.codePoints().forEach(cp -> {
					if (ui && ADVANCE_BY_CP.containsKey(cp)) {
						total[0] += ADVANCE_BY_CP.get(cp);
					} else {
						total[0] += WIDTHS.getOrDefault(cp, defaultWidth) + (bold && cp != ' ' ? 1 : 0);
					}
				});
				return Optional.empty();
			}, style);
		}
		for (Component sib : c.getSiblings()) measure(sib, style, total);
	}

	public static int width(List<? extends Component> lines) {
		int w = 0;
		for (Component c : lines) w = Math.max(w, width(c));
		return w;
	}

	/** "▮▮▮▯▯" as rounded pips: {@code full} of {@code total} filled in {@code rgb}. */
	public static MutableComponent pips(int full, int total, int rgb) {
		full = Math.max(0, Math.min(total, full));
		return Component.empty()
				.append(ui(g("pip.full").repeat(full), rgb))
				.append(ui(g("pip.empty").repeat(total - full)));
	}

	/** A small 8x8 picture (heart, sprout, chest …) followed by a 2 px gap. */
	public static MutableComponent icon(String name) {
		return ui(g("icon." + name) + space(2));
	}

	/** The ornamental rule ──◆── exactly {@code w} pixels wide. */
	public static MutableComponent divider(int w) {
		int ends = advance("div.l") - 1 + advance("div.r") - 1 + advance("div.c") - 1;
		int rest = Math.max(0, w - ends);
		int left = rest / 2;
		String back = g("space-1");
		return ui(g("div.l") + back + tiles("div.m", left) + g("div.c") + back + tiles("div.m", rest - left) + g("div.r") + back);
	}

	/** The tooltip panel for {@code lines} lines of content, {@code innerW} wide (padding comes on top). */
	public static MutableComponent panel(int lines, int innerW) {
		int n = Math.max(minPanel, Math.min(maxPanel, lines));
		int w = innerW + 2 * padX;
		String back = g("space-1");
		return ui(g("panel" + n + ".l") + back + tiles("panel" + n + ".m", w - 12) + g("panel" + n + ".r") + back);
	}

	/** Font for line {@code line} of the top-of-screen tooltip (everything moved down one line per font). */
	public static FontDescription hud(int line) {
		return new FontDescription.Resource(Identifier.fromNamespaceAndPath("libreria", "hud" + line));
	}

	/** Item pictures at full size, for buttons in a window (a dialog). */
	public static final FontDescription ICON_FONT = new FontDescription.Resource(Identifier.fromNamespaceAndPath("libreria", "icons"));

	/**
	 * An item's picture inside a 20 px button of a window, followed by space up to {@code column} px; null when the
	 * item has no picture (modded items, or ones drawn by special renderers).
	 */
	@org.jetbrains.annotations.Nullable
	public static MutableComponent buttonIcon(net.minecraft.world.item.Item item, int column) {
		int[] ic = icon(item);
		if (ic == null) return null;
		int color = ic[1] == 1 ? 0x6AA84F : 0xFFFFFF;
		return Component.empty()
				.append(Component.literal(Character.toString(ic[0])).withStyle(st -> st.withFont(ICON_FONT).withoutShadow().withColor(color)))
				.append(ui(space(column - ic[2])));
	}

	/** {codepoint, tinted (1/0), advance} of an item's icon for the top tooltip, or null. */
	@org.jetbrains.annotations.Nullable
	public static int[] icon(net.minecraft.world.item.Item item) {
		Identifier id = net.minecraft.core.registries.BuiltInRegistries.ITEM.getKey(item);
		return id.getNamespace().equals("minecraft") ? ICONS.get(id.getPath()) : null;
	}

	/**
	 * The same text in another font (deeply: every part). Pictures from the UI font lose their shadow when
	 * {@code noShadowOnPictures} is set (a boss bar title always draws a shadow).
	 */
	public static MutableComponent inFont(Component c, FontDescription font, boolean noShadowOnPictures) {
		Style st = c.getStyle();
		boolean picture = st.getFont() instanceof FontDescription.Resource r && r.id().getNamespace().equals("libreria");
		Style ns = st.withFont(font);
		if (picture && noShadowOnPictures) ns = ns.withoutShadow();
		MutableComponent out = c.plainCopy().setStyle(ns);
		for (Component sib : c.getSiblings()) out.append(inFont(sib, font, noShadowOnPictures));
		return out;
	}

	/** A container title with the themed frame of a tool drawn behind the whole window. */
	public static MutableComponent framedTitle(String theme, int rows, Component title) {
		String name = "frame" + rows + "." + theme;
		if (!has(name)) name = "frame" + rows + ".libreria";
		if (!has(name)) return title.copy();
		int adv = advance(name);
		return Component.empty()
				.append(ui(space(-8) + g(name) + space(-(adv - 8)), 0xFFFFFF))
				.append(title);
	}
}
